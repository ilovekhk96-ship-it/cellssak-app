// 블록 클러스터로 전부 교체함. 버전3과 같은 방식(가지만 있는 나무 사진을 격자로
// 스캔해 실제 가지 픽셀만 앵커로 씀, 몸통·뿌리 제외, 두께에 따라 앞/뒤 두 그룹)을 그대로
// 따름. v2, v3와 완전히 분리된 파일이라 이 파일을 고쳐도 실제 서비스나 다른 버전에는
// 영향 없음.

function seededRandom(seed) {
  let s = seed | 0;
  return function () {
    s = (s + 0x6d2b79f5) | 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffledAnchors(list) {
  const arr = [...list];
  const rand = seededRandom(20260921);
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

