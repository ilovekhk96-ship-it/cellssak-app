export function getLeafV4(index) {
  const anchor = LEAF_ANCHORS_V4[index % LEAF_ANCHORS_V4.length];
  const ring = Math.floor(index / LEAF_ANCHORS_V4.length);
  const rand = seededRandom(index * 2654435761 + 7);
  const anchorAngleRad = (anchor.angle * Math.PI) / 180;
  let jitterAngle;
  let radius;
  if (ring === 0) {
    jitterAngle = rand() * Math.PI * 2;
    radius = 0.8 + rand() * 0.8;
  } else {
    jitterAngle = anchorAngleRad + (rand() - 0.5) * Math.PI * 0.9;
    radius = 1 + Math.min(ring * 0.3, 4) + rand() * 0.9;
  }
  const variant = LEAF_IMAGES_V4[index % LEAF_IMAGES_V4.length];
  const rot = (rand() - 0.5) * 60;
  return {
    x: anchor.x + Math.cos(jitterAngle) * radius,
    y: anchor.y + Math.sin(jitterAngle) * radius * 0.85,
    rot,
    scale: 0.6 + rand() * 0.3,
    variant,
    behind: anchor.behind,
  };
}

export const FRUIT_SPOTS_V4 = LEAF_ANCHORS_V4.filter((_, i) => i % 5 === 0).map((a) => ({ x: a.x, y: a.y, behind: a.behind }));
