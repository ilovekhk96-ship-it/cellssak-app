// 트렁크에 바로 붙은 가장 굵은 가지(6~10대)에는 잎을 붙이지 않아야 이끼처럼 뭉치지 않고
// 실제 나무처럼 가장자리 위주로 무성해짐. angle은 그 가지가 자라난 방향(도) — 잎이 그 방향을 향하게 함
const ANCHOR_POSITIONS_ALONG_BRANCH = [0.5, 0.75, 1];
