export const STAGE_THRESHOLDS = [1, 3, 8, 15, 25, 40];
export const STAGE_LABELS = [
  '씨앗을 심었어요',
  '작은 새싹이 돋았어요',
  '어린 나무가 되었어요',
  '가지가 뻗어가고 있어요',
  '잎이 무성해지고 있어요',
  '풍성한 나무가 되었어요',
  '우리 셀의 나무가 활짝 무성해요',
];

export function getStage(score) {
  let stage = 0;
  STAGE_THRESHOLDS.forEach((t) => {
    if (score >= t) stage += 1;
  });
  return Math.min(stage, STAGE_THRESHOLDS.length);
}

export function getIndexLabel(name) {
  const ch = (name || '').trim()[0];
  if (!ch) return '#';
  const code = ch.charCodeAt(0);
  if (code >= 0xac00 && code <= 0xd7a3) {
    const choIdx = Math.floor((code - 0xac00) / 588);
    const cho = CHO[choIdx];
    return BASE_MAP[cho] || cho;
  }
  const upper = ch.toUpperCase();
  if (upper >= 'A' && upper <= 'Z') return upper;
  return '#';
}

const KST_DATE_FORMATTER = new Intl.DateTimeFormat('en-CA', {
  timeZone: 'Asia/Seoul',
  year: 'numeric',
  month: '2-digit',
  day: '2-digit',
});

// 한국 표준시(KST) 기준 오늘 날짜 — 날짜 경계(자정)가 사용자 브라우저 시간대와 무관하게 항상 한국 기준이어야 함
export function todayStr() {
  return KST_DATE_FORMATTER.format(new Date());
}
