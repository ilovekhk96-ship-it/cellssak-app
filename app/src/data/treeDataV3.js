export function getLeafV3(index) {
  const anchor = LEAF_ANCHORS_V3[index % LEAF_ANCHORS_V3.length];
  const ring = Math.floor(index / LEAF_ANCHORS_V3.length);
  const rand = seededRandom(index * 2654435761 + 7);
  const anchorAngleRad = (anchor.angle * Math.PI) / 180;
  let jitterAngle;
  let radius;
  if (ring === 0) {
    jitterAngle = rand() * Math.PI * 2;
    radius = 2 + rand() * 1.8;
  } else {
    jitterAngle = anchorAngleRad + (rand() - 0.5) * Math.PI * 0.9;
    radius = 4 + Math.min(ring * 0.9, 14) + rand() * 2.4;
  }
  const rot = rand() * 360;
  return {
    x: anchor.x + Math.cos(jitterAngle) * radius,
    y: anchor.y + Math.sin(jitterAngle) * radius * 0.85,
    rot,
    scale: 0.85 + rand() * 0.5,
    variant: LEAF_IMAGES_V3[index % LEAF_IMAGES_V3.length],
  };
}

