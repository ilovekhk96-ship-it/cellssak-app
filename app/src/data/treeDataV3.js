// 갈수록 좁아지는 사다리꼴 모양의 "몸통 제외 구역"에 들어가는 점은 전부 걸러냄 —
// 그 결과 가지가 갈라져 뻗어나가는 잔가지 부분에만 앵커가 남음.
// 잎은 사용자가 보내준 낱장 잎사귀 시트에서 잘라낸 21종을 순환시켜 사용.
// v2(현재 라이브)와 완전히 분리된 파일이라 이 파일을 고쳐도 실제 서비스에는 영향 없음.

function seededRandom(seed) {
  let s = seed | 0;
  return function () {
    s = (s + 0x6d2b79f5) | 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffledAnchors(list) {
  const arr = [...list];
  const rand = seededRandom(20260917);
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

